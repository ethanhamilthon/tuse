local font = {}
for k, v in pairs(U) do font[k] = v end
for k, v in pairs(L) do font[k] = v end

local ROWS = 9

local function glyph(ch)
    local g = font[ch] or font[ch:upper()] or font[ch:lower()] or font["_"]
    local w = 0
    for _, r in ipairs(g) do w = math.max(w, #r) end
    return g, w
end

local function render(text)
    local rows = {}
    for r = 1, ROWS do rows[r] = {} end
    local first = true
    for ch in text:gmatch(".") do
        local g, w = glyph(ch)
        for r = 1, ROWS do
            if not first then table.insert(rows[r], false) end
            local line = g[r] or ""
            for c = 1, w do table.insert(rows[r], line:sub(c, c) == "#") end
        end
        first = false
    end
    local out = {}
    for r = 1, ROWS do
        local chars = { " " }
        for _, on in ipairs(rows[r]) do
            local s = on and "█" or " "
            chars[#chars + 1] = s
            chars[#chars + 1] = s
        end
        for i = 1, #chars - 1 do
            if chars[i] == " " and chars[i + 1] == "█" then chars[i] = "░" end
        end
        out[r] = (table.concat(chars):gsub("%s+$", ""))
    end
    while #out > 0 and out[#out] == "" do out[#out] = nil end
    return out
end

return { render = render }
